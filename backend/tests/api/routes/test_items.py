import uuid

from fastapi.testclient import TestClient
from sqlmodel import Session

from app.core.config import settings
from tests.utils.item import create_random_item


def test_create_item(
    client: TestClient, superuser_token_headers: dict[str, str]
) -> None:
    data = {"title": "Foo", "description": "Fighters"}
    response = client.post(
        f"{settings.API_V1_STR}/items/",
        headers=superuser_token_headers,
        json=data,
    )
    assert response.status_code == 200
    content = response.json()
    assert content["title"] == data["title"]
    assert content["description"] == data["description"]
    assert "id" in content
    assert "owner_id" in content


def test_duplicate_item(
    client: TestClient, normal_user_token_headers: dict[str, str]
) -> None:
    items_url = f"{settings.API_V1_STR}/items"
    created = client.post(
        f"{items_url}/",
        headers=normal_user_token_headers,
        json={"title": "Original", "description": "Copy this description"},
    )
    assert created.status_code == 200
    original = created.json()

    response = client.post(
        f"{items_url}/{original['id']}/duplicate", headers=normal_user_token_headers
    )
    assert response.status_code == 201
    duplicate = response.json()
    assert duplicate["id"] != original["id"]
    assert duplicate["owner_id"] == original["owner_id"]
    assert duplicate["title"] == original["title"]
    assert duplicate["description"] == original["description"]

    saved = client.get(
        f"{items_url}/{duplicate['id']}", headers=normal_user_token_headers
    )
    assert saved.status_code == 200
    assert saved.json() == duplicate


